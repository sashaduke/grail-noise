// Emits lib/noise_tables.grl: FastNoiseLite 1.1.1's 2D lookup tables and the float constants its
// 2D kernels fold at compile time, each as the exact binary64 value of the binary32 constant, so
// Grail's f32() reproduces the same bits (no decimal double rounding).
//   clang++ -std=c++17 -O0 -I<fastnoiselite>/include noise_tables.cpp -o tables && ./tables > ../../../lib/noise_tables.grl
#define private public
#include <FastNoiseLite.h>
#undef private
#include <cstdio>

// A Grail f64 literal: %.17g round-trips binary64, plus ".0" when it would read as an integer.
static void lit(double v) {
    char buf[64];
    std::snprintf(buf, sizeof buf, "%.17g", v);
    bool plain = true;
    for (const char *c = buf; *c; ++c)
        if (*c == '.' || *c == 'e' || *c == 'n' || *c == 'i') plain = false;
    std::printf("%s%s", buf, plain ? ".0" : "");
}
static void table(const char *name, const float *v, int n) {
    std::printf("pub fn %s() -> f32[] {\n    values := f64[", name);
    for (int i = 0; i < n; ++i) {
        std::printf("%s", i ? ", " : "");
        lit((double)v[i]);
    }
    std::printf("];\n    mut out = f32[];\n    for i in values.len() {\n        out.push(f32(values[i]));\n    }\n    return out;\n}\n");
}
static void constant(const char *name, float v) {
    std::printf("pub fn %s() -> f32 {\n    return f32(%.17g);\n}\n", name, (double)v);
}
int main() {
    std::printf("module noise_tables;\n\n// Generated by tests/reference/noise/noise_tables.cpp from FastNoiseLite 1.1.1\n");
    std::printf("// (MIT, Copyright (c) 2023 Jordan Peck, Copyright (c) 2023 Contributors); do not edit.\n\n");
    table("gradients_2d", FastNoiseLite::Lookup<float>::Gradients2D, 256);
    table("rand_vecs_2d", FastNoiseLite::Lookup<float>::RandVecs2D, 512);
    table("gradients_3d", FastNoiseLite::Lookup<float>::Gradients3D, 256);
    // OpenSimplex2 (float SQRT3/G2) folded constants, as the compiler evaluates them in float.
    const float SQRT3 = 1.7320508075688772935274463415059f;
    const float G2 = (3 - SQRT3) / 6;
    constant("os2_g2", G2);
    constant("os2_c1", (float)(2 * (1 - 2 * G2) * (1 / G2 - 2)));
    constant("os2_c2", (float)(-2 * (1 - 2 * G2) * (1 - 2 * G2)));
    constant("os2_x2", (2 * (float)G2 - 1));
    constant("os2_g2m1", ((float)G2 - 1));
    // OpenSimplex2S (double SQRT3/G2) constants cast to float.
    const double SQRT3d = 1.7320508075688772935274463415059;
    const double G2d = (3 - SQRT3d) / 6;
    constant("os2s_g2", (float)G2d);
    constant("os2s_c1", (float)(2 * (1 - 2 * G2d) * (1 / G2d - 2)));
    constant("os2s_c2", (float)(-2 * (1 - 2 * G2d) * (1 - 2 * G2d)));
    constant("os2s_1m2g2", (float)(1 - 2 * G2d));
    constant("os2s_3g2m2", (float)(3 * G2d - 2));
    constant("os2s_3g2m1", (float)(3 * G2d - 1));
    constant("os2s_g2m1", (float)(G2d - 1));
    constant("os2s_1mg2", (float)(1 - G2d));
    constant("two_thirds", 2.0f / 3.0f);
    constant("os2_scale", 99.83685446303647f);
    constant("os2s_scale", 18.24196194486065f);
    constant("os2s3_scale", 9.046026385208288f);
    constant("perlin_scale", 1.4247691104677813f);
    constant("cell_jitter", 0.43701595f);
    constant("cell_far", 1e10f);
    constant("warp_os2_amp", 38.283687591552734375f);
    constant("inv_2_31", 1 / 2147483648.0f);
    constant("default_bounding", 1 / 1.75f);
    return 0;
}
